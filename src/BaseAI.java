import java.util.ArrayList; // Робочий потік керує власною змінною колекцією машин.
import java.util.List; // Публікуємо знімки через інтерфейс List.
import java.util.Random; // Відтворюваний генератор потрібен для демонстрації й тестування.
// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
// extends задає єдиний батьківський клас. Виклик методу через змінну базового типу все одно обирає реалізацію
// фактичного об’єкта — так працює поліморфізм, знайомий і з Python.
// Об’єкт самого abstract-класу створити не можна. Він зберігає спільні півосі чи механізм роботи, а відсутні
// реалізації методів надають підкласи; перевірка цього обов’язку відбувається під час компіляції.
public abstract class BaseAI extends Thread { // Абстрактний інтелект виконаний окремим потоком згідно з умовою.
    // private забороняє прямий доступ до поля з інших класів. final дозволяє присвоїти поле лише один раз; для
    // посилання це заборона замінити об’єкт, а не заборона змінювати його вміст, якщо сам об’єкт змінний.
    private final Object gate = new Object(); // Монітор для узгодження паузи, відновлення й кроку руху.
    // ArrayList — список, що може змінювати довжину, найближчий тут до Python list. Тип у <...> обмежує допустимі
    // елементи під час компіляції; <> після new означає «вивести цей тип із контексту». Конструктор із колекцією
    // копіює список посилань, а не самі об’єкти.
    private final ArrayList<Vehicle> vehicles = new ArrayList<>(); // Лише цей потік змінює позиції своїх машин.
    // of(...) створює незмінювану колекцію: додавання або видалення після створення спричинить
    // UnsupportedOperationException. Для змінної копії її передають у new ArrayList<>(...) чи new HashSet<>(...).
    // volatile забезпечує видимість нового значення для інших потоків і публікацію попередніх записів. Це не замок
    // і не робить довільну складену операцію атомарною: список тут додатково незмінюваний, а для узгодження паузи
    // використано synchronized.
    private volatile List<Position> positions = List.of(); // volatile безпечно публікує повністю готовий незмінний знімок для EDT.
    private volatile boolean running = true; // Прапорець завершення має бути видимим робочому потоку.
    // Це поле не volatile, бо кожне читання і запис після запуску захищені одним synchronized(gate). Замок
    // забезпечує і взаємне виключення, і видимість значення; змішувати доступ під замком та без нього тут не
    // можна.
    private boolean paused = false; // Прапорець паузи читається й змінюється лише під gate.
    protected BaseAI(String name, boolean truck, Organization owner, long seed) { // Спільна підготовка обох видів інтелекту.
        // super(...) викликає конструктор батьківського класу для цього самого об’єкта, приблизно як
        // super().__init__(...) у Python. У цих проєктах із рівнем Java 17 цей виклик стоїть першим у
        // конструкторі: спочатку готуємо батьківську частину, потім власні поля.
        super(name); // Задаємо зрозуміле ім'я Java-потоку.
        // Зерно seed задає відтворювану послідовність псевдовипадкових чисел. Однакове зерно й однаковий порядок
        // викликів дають той самий початок симуляції; це допомагає повторювати перевірки.
        Random random = new Random(seed); // Однакове зерно відтворює початкові дані.
        // У for спочатку один раз задається лічильник, перед кожним проходом перевіряється умова, а після проходу
        // виконується i++ або j++. Умова i < n відповідає Python range(n): значення n вже не входить у цикл.
        for (int i = 1; i <= 8; i++) vehicles.add(new Vehicle(i, owner, truck, random)); // Створюємо колекцію з восьми машин потрібного типу.
        publish(); // Початковий знімок доступний ще до Thread.start.
    }
    // abstract означає, що тут задані лише назва, параметри й тип результату методу. Тіла немає: конкретний
    // підклас мусить надати його, приблизно як метод з @abstractmethod у Python.
    protected abstract double speed(); // Кожен конкретний інтелект визначає швидкість свого виду машин.
    private void publish() { // Передаємо дані в основний потік GUI через незмінні повідомлення.
        // stream() перебирає машини як потік даних, без створення нового потоку виконання. map(Vehicle::snapshot)
        // викликає snapshot для кожної машини — як [v.snapshot() for v in vehicles] у Python. toList() тут дає
        // незмінюваний список, який одним присвоєнням positions публікується для GUI.
        positions = vehicles.stream().map(Vehicle::snapshot).toList(); // toList створює немодифікований список нових Position.
    }
    public List<Position> snapshots() { return positions; } // EDT читає останній повний знімок без блокування малювання.
    public void setPaused(boolean value) { // GUI або консоль керує паузою через цей метод.
        // synchronized(gate) дозволяє лише одному потоку одночасно виконувати блок під цим самим замком. При
        // виході замок звільняється навіть через виняток; близький задум у Python — with lock. Один gate для паузи
        // й кроку не дає їм виконуватися одночасно.
        synchronized (gate) { // Той самий монітор не дозволяє одночасно виконати крок і змінити паузу.
            paused = value; // Зберігаємо запитаний стан.
            // notifyAll будить усіх, хто чекає на цьому самому gate, але не віддає замок негайно. Пробуджений
            // потік продовжить після звільнення замка й знову перевірить paused/running; саме сповіщення ще не
            // означає «можна рухатися».
            gate.notifyAll(); // Будимо потік, щоб він повторно перевірив умову очікування.
        }
    }
    public void shutdown() { // Кооперативне завершення замість небезпечного Thread.stop.
        running = false; // Просимо основний цикл завершитися.
        synchronized (gate) { gate.notifyAll(); } // Будимо також потік, який зараз чекає на паузі.
        // interrupt() надсилає цьому робочому потоку запит на переривання. Він не вбиває потік: sleep або wait
        // реагують InterruptedException, після чого run виходить; прапорець running також зупиняє звичайний прохід
        // циклу.
        interrupt(); // Перериваємо sleep або wait для швидкого закриття.
    }
    // @Override просить компілятор перевірити, що метод справді замінює успадкований метод або реалізує метод
    // інтерфейсу. Якщо помилитися в назві чи параметрах, Java повідомить про це ще до запуску.
    @Override public final void run() { // start створює потік, а JVM викликає цей метод у ньому.
        // nanoTime — годинник для вимірювання проміжків, як time.perf_counter_ns() у Python. Його значення не є
        // календарною датою; зміст має різниця двох показів, яку не збиває переведення системного годинника.
        // У run відлік часу береться до першого кроку, а після повернення з wait — заново. Так час, проведений на
        // паузі, не перетворюється на великий стрибок координат.
        long previous = System.nanoTime(); // Початковий момент для розрахунку dt.
        try { // InterruptedException використовується як штатний сигнал завершення.
            while (running) { // Цикл триває до shutdown.
                synchronized (gate) { // Узгоджуємо весь крок руху з керуванням паузою.
                    while (paused && running) { // while потрібен через можливі спонтанні пробудження wait.
                        // wait() можна викликати, лише володіючи замком gate: метод засинає й тимчасово ВІДДАЄ цей
                        // замок, щоб інший потік міг змінити paused. Перед поверненням з wait замок береться
                        // знову; while повторно перевіряє умову навіть після випадкового пробудження. Близький
                        // аналог — threading.Condition.wait().
                        gate.wait(); // Потік засинає та звільняє монітор, не витрачаючи CPU на активне очікування.
                        previous = System.nanoTime(); // Час паузи не додається до переміщення після відновлення.
                    }
                    // Потік могли розбудити не для продовження руху, а для закриття. break виходить із найближчого
                    // зовнішнього while, тому останній зайвий крок руху не виконується.
                    if (!running) break; // Після пробудження перевіряємо, чи не надійшло завершення.
                    long now = System.nanoTime(); // Поточний монотонний час.
                    // У наносекунді 1/1_000_000_000 секунди, тому ділимо різницю на мільярд. .0 робить ділення
                    // дробовим, а підкреслення лише полегшують читання числа й не впливають на значення.
                    double dt = (now - previous) / 1_000_000_000.0; // Фактичний проміжок часу у секундах.
                    previous = now; // Оновлюємо відлік наступного кроку.
                    // Це for-each: двокрапка означає «взяти по черзі кожен елемент», як for item in items у
                    // Python. Ліворуч указано тип елемента; сам індекс тут не потрібен, а для об’єктів змінна
                    // отримує посилання, не копію.
                    for (Vehicle vehicle : vehicles) vehicle.move(speed(), dt); // Оновлюємо кожну машину тільки у власному потоці.
                    publish(); // Після завершення всього кроку атомарно публікуємо новий список.
                }
                // sleep призупиняє ПОТОЧНИЙ потік на задану кількість мілісекунд і може кинути
                // InterruptedException. Інші потоки працюють далі; на відміну від wait, sleep не віддає вже
                // захоплених замків, тому в BaseAI він стоїть поза synchronized.
                Thread.sleep(16); // Обмежуємо частоту кроків, звільняючи процесор між ними.
            }
        // catch — аналог except у Python: ця гілка виконується лише після відповідної помилки в try. e — об’єкт
        // винятку, getMessage() дає його пояснення; вертикальна риска між типами дозволяє одним блоком обробити
        // кілька видів помилок.
        // Коли sleep/wait кидає InterruptedException, стан переривання очищується. Відновлюємо його через
        // currentThread().interrupt(), щоб не загубити сигнал завершення; після catch метод run закінчується.
        } catch (InterruptedException e) { Thread.currentThread().interrupt(); } // Відновлюємо прапорець переривання перед виходом із run.
    }
}
