// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
public class Organization { // Базовий клас для всіх організацій; також використовується в лабораторній 7.
    // private забороняє прямий доступ до поля з інших класів. final дозволяє присвоїти поле лише один раз; для
    // посилання це заборона замінити об’єкт, а не заборона змінювати його вміст, якщо сам об’єкт змінний.
    private final String name; // Назва є спільною властивістю всіх організацій.
    private final String address; // Адресу зберігаємо в базовому класі, не дублюючи в підкласах.
    public Organization(String name, String address) { // Конструктор спільних даних.
        // isBlank() істинний для порожнього рядка або рядка лише з пробільних символів за правилами Java. Це
        // перевірка змістовного введення; isEmpty() перевірив би тільки нульову довжину.
        // throw — аналог raise у Python: негайно припиняємо звичайний хід методу й передаємо об’єкт помилки
        // найближчому відповідному catch. new створює виняток, а текст конструктора пояснює причину користувачу.
        if (name.isBlank() || address.isBlank()) throw new IllegalArgumentException("Назва й адреса не можуть бути порожні."); // Зберігаємо інваріант змістовних полів.
        // this — поточний об’єкт, аналог self у Python, але його не пишуть у списку параметрів. Ліворуч this.ім’я
        // — поле об’єкта, праворуч однойменне ім’я без this — переданий параметр; тому значення зберігається після
        // завершення конструктора.
        this.name = name; // Ініціалізуємо назву поточного об'єкта.
        this.address = address; // Ініціалізуємо адресу.
    }
    public String getName() { return name; } // Підкласи та інші об'єкти можуть читати назву.
    public void Show() { System.out.println(this); } // Динамічний виклик toString відображає фактичний підклас.
    // @Override просить компілятор перевірити, що метод справді замінює успадкований метод або реалізує метод
    // інтерфейсу. Якщо помилитися в назві чи параметрах, Java повідомить про це ще до запуску.
    @Override public String toString() { return name + "; адреса: " + address; } // Формуємо спільну частину опису.
}
