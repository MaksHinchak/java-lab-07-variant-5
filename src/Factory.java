// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
// extends задає єдиний батьківський клас. Виклик методу через змінну базового типу все одно обирає реалізацію
// фактичного об’єкта — так працює поліморфізм, знайомий і з Python.
public final class Factory extends Organization { // Похідний клас успадковує назву, адресу та Show.
    // private забороняє прямий доступ до поля з інших класів. final дозволяє присвоїти поле лише один раз; для
    // посилання це заборона замінити об’єкт, а не заборона змінювати його вміст, якщо сам об’єкт змінний.
    private final int workers; // Власна характеристика: кількість працівників.
    public Factory(String name, String address, int workers) { // Конструктор отримує спільні та спеціальні дані.
        // super(...) викликає конструктор батьківського класу для цього самого об’єкта, приблизно як
        // super().__init__(...) у Python. У цих проєктах із рівнем Java 17 цей виклик стоїть першим у
        // конструкторі: спочатку готуємо батьківську частину, потім власні поля.
        super(name, address); // Спочатку викликаємо конструктор батьківської організації.
        // throw — аналог raise у Python: негайно припиняємо звичайний хід методу й передаємо об’єкт помилки
        // найближчому відповідному catch. new створює виняток, а текст конструктора пояснює причину користувачу.
        if (workers < 0) throw new IllegalArgumentException("Кількість не може бути від'ємною."); // Перевіряємо спеціальне поле.
        // this — поточний об’єкт, аналог self у Python, але його не пишуть у списку параметрів. Ліворуч this.ім’я
        // — поле об’єкта, праворуч однойменне ім’я без this — переданий параметр; тому значення зберігається після
        // завершення конструктора.
        this.workers = workers; // Зберігаємо перевірену кількість.
    }
    // @Override просить компілятор перевірити, що метод справді замінює успадкований метод або реалізує метод
    // інтерфейсу. Якщо помилитися в назві чи параметрах, Java повідомить про це ще до запуску.
    @Override public void Show() { System.out.println(this); } // Реалізуємо потрібний у методичці метод для цього підкласу.
    // super.toString() бере опис базової частини поточного об’єкта, до якого додаємо спеціальну властивість
    // підкласу. Виклик просто toString() тут знову викликав би цей самий метод і спричинив нескінченну рекурсію.
    @Override public String toString() { return "Factory: " + super.toString() + "; працівників: " + workers; } // Доповнюємо батьківський опис власною властивістю.
}
