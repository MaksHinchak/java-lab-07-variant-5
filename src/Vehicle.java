import java.util.Random; // Генеруємо початкові та кінцеві координати в дозволених областях.
// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
public final class Vehicle { // Змінний стан однієї машини належить лише одному потоку BaseAI.
    // static означає одне спільне поле класу, а final — заборону повторного присвоєння. Таку константу читають
    // через ім’я класу без створення об’єкта; великі літери в назві — домовленість Java, а не окремий синтаксис.
    public static final int WIDTH = 760; // Ширина логічної області симуляції не залежить від розміру вікна.
    public static final int HEIGHT = 440; // Висота логічної області руху.
    // private забороняє прямий доступ до поля з інших класів. final дозволяє присвоїти поле лише один раз; для
    // посилання це заборона замінити об’єкт, а не заборона змінювати його вміст, якщо сам об’єкт змінний.
    private final int id; // Номер машини для ідентифікації на малюнку та у виводі.
    private final Organization owner; // Зберігаємо зв'язок з ієрархією організацій із лабораторної 3, завдання 1.
    private double x; // Поточна горизонтальна координата, яку змінює тільки робочий потік.
    private double y; // Поточна вертикальна координата.
    private final double targetX; // Кінцева точка вибирається один раз при народженні машини.
    private final double targetY; // Після прибуття нову ціль не призначаємо.
    public Vehicle(int id, Organization owner, boolean truck, Random random) { // Прапорець truck визначає цільову чверть.
        // this — поточний об’єкт, аналог self у Python, але його не пишуть у списку параметрів. Ліворуч this.ім’я
        // — поле об’єкта, праворуч однойменне ім’я без this — переданий параметр; тому значення зберігається після
        // завершення конструктора.
        this.id = id; // Запам'ятовуємо номер.
        this.owner = owner; // Машина належить заданій організації.
        // nextDouble() повертає значення від 0 включно до 1 невключно, як random.random() у Python. Множення
        // розтягує його на потрібну ширину або висоту, а додавання offset переносить у потрібну половину області.
        x = random.nextDouble() * WIDTH; // Випадкове народження по всій ширині області.
        y = random.nextDouble() * HEIGHT; // Випадкове народження по всій висоті.
        // Умова ? значення_якщо_так : значення_якщо_ні — короткий вибір одного з двох значень, аналог a if
        // condition else b у Python. Обчислюється лише вибрана частина, тому інший конструктор чи виклик тут не
        // виконується.
        // Координати відлічуються від верхнього лівого кута: менший y означає вище. Для вантажівки цільова чверть
        // верхня ліва, для легкової — нижня права; середні лінії включено умовами <= та >=.
        boolean inside = truck ? x <= WIDTH / 2.0 && y <= HEIGHT / 2.0 : x >= WIDTH / 2.0 && y >= HEIGHT / 2.0; // Перевіряємо, чи машина вже у своїй цільовій чверті.
        double offsetX = truck ? 0 : WIDTH / 2.0; // Вантажівки мають ліву, легкові - праву половину.
        double offsetY = truck ? 0 : HEIGHT / 2.0; // Вантажівки мають верхню, легкові - нижню половину.
        // Якщо початок уже в цільовій чверті, ціль дорівнює початку й машина одразу прибула. Інакше випадкова
        // координата обмежена потрібною половиною розміру; нові цілі після прибуття не вибираються.
        targetX = inside ? x : offsetX + random.nextDouble() * WIDTH / 2.0; // Машина, народжена в потрібній чверті, залишається на місці.
        targetY = inside ? y : offsetY + random.nextDouble() * HEIGHT / 2.0; // Інакше обираємо випадкову кінцеву точку потрібної чверті.
    }
    public void move(double speed, double seconds) { // Пересуваємо машину прямолінійно на відстань V*dt.
        // Double.isFinite(...) повертає true лише для звичайного скінченного числа; ! заперечує результат. double
        // може містити NaN («не число») і ±Infinity, тому успішний parseDouble ще не гарантує придатність числа
        // для формули. У Python аналог — math.isfinite(x); ця перевірка не перевіряє точність округлення.
        // throw — аналог raise у Python: негайно припиняємо звичайний хід методу й передаємо об’єкт помилки
        // найближчому відповідному catch. new створює виняток, а текст конструктора пояснює причину користувачу.
        if (!Double.isFinite(speed) || speed < 0 || !Double.isFinite(seconds) || seconds < 0) throw new IllegalArgumentException("Швидкість і час мають бути скінченними та невід'ємними."); // Забороняємо некоректний крок інтегрування.
        double dx = targetX - x; // Горизонтальна складова вектора до цілі.
        double dy = targetY - y; // Вертикальна складова вектора до цілі.
        // hypot(dx, dy) обчислює довжину sqrt(dx² + dy²) з кращим захистом від проміжного переповнення, ніж пряме
        // піднесення до квадратів. Тут це відстань між двома точками, аналог math.hypot у Python.
        double distance = Math.hypot(dx, dy); // Евклідова довжина цього вектора.
        if (distance == 0) return; // Прибуття означає остаточну зупинку.
        // Швидкість задається в логічних пікселях за секунду, час — у секундах, тому добуток є відстанню за
        // поточний крок. Відстань не прив’язана до кількості кадрів: затримка кадру враховується через фактичний
        // час.
        double step = speed * seconds; // Відстань, яку можна пройти за поточний проміжок часу.
        // Якщо машина за цей крок могла б пройти далі цілі, ставимо x/y рівно в targetX/targetY. Це прибирає
        // проскок і робить перевірку arrived через точне == коректною після прибуття.
        if (step >= distance) { // Не дозволяємо проскочити кінцеву точку.
            x = targetX; // Точно встановлюємо кінцеву координату x.
            y = targetY; // Точно встановлюємо кінцеву координату y.
        } else { // Залишок шляху більший за один крок.
            // Ділення на distance дає складову одиничного напрямку, а множення на step — потрібне зміщення за цей
            // кадр. Випадок нульової distance уже завершив метод вище, тому ділення на нуль тут немає.
            x += dx / distance * step; // Нормалізуємо напрям і додаємо горизонтальне зміщення.
            y += dy / distance * step; // Так само обчислюємо вертикальне зміщення.
        }
    }
    // Створюємо новий знімок зі значеннями на цю мить. GUI отримує його замість доступу до змінних x/y машини,
    // тому не може побачити половину оновлення координат або сам змінити рух.
    public Position snapshot() { return new Position(id, x, y, targetX, targetY, owner.getName(), x == targetX && y == targetY); } // Створюємо незалежне незмінне повідомлення для GUI.
}
