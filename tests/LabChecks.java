// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
public class LabChecks { // Автономні перевірки без зовнішніх бібліотек тестування.
    private static int count = 0; // Лічильник успішно перевірених умов.
    // static означає, що метод належить класу: його можна викликати без створення об’єкта. public дозволяє виклик
    // з інших класів, private обмежує використання цим класом; тип перед назвою задає результат, а void означає
    // відсутність значення для повернення.
    private static void check(boolean value) { // Допоміжний метод перетворює хибну умову на провал тесту.
        // throw — аналог raise у Python: негайно припиняємо звичайний хід методу й передаємо об’єкт помилки
        // найближчому відповідному catch. new створює виняток, а текст конструктора пояснює причину користувачу.
        // AssertionError тут явно позначає провал перевірки: тест зупиниться і покаже причину. На відміну від
        // ключового слова assert у Java, такий throw працює завжди, навіть без прапорця запуску -ea.
        if (!value) throw new AssertionError("Перевірка " + (count + 1) + " не пройшла."); // Зупиняємо тест із ненульовим кодом процесу.
        count++; // Рахуємо лише успішні перевірки.
    }
    private static void near(double actual, double expected) { // Порівнюємо double з допуском на округлення.
        // double зберігає двійкове наближення, тому очікуємо малу похибку, а не точне ==. Беремо більшу з
        // абсолютної межі 1e-9 та відносної 1e-9*abs(expected), приблизно як math.isclose з відповідними допусками
        // у Python.
        check(Math.abs(actual - expected) <= 1e-9 * Math.max(1, Math.abs(expected))); // Допуск враховує масштаб очікуваного числа.
    }
    // throws у заголовку попереджає викликача про перевірюваний виняток: Java вимагає його перехопити або теж
    // оголосити throws. Це не команда кинути помилку — її кидає throw усередині; у Python такої обов’язкової
    // декларації немає.
    // Цей маленький інтерфейс описує одну дію run(), тому його можна передати лямбдою () -> ... . throws Exception
    // дозволяє тестувати й методи з перевірюваними винятками; сама дія виконається всередині expect, де її помилка
    // буде перевірена.
    private interface Action { void run() throws Exception; } // Лямбда тесту може породжувати і перевірювані винятки.
    // Class зберігає опис типу, наприклад ArithmeticException.class. ? extends Throwable означає «якийсь тип
    // помилки, що успадковує Throwable»; isInstance перевіряє відповідність, як isinstance(error, expected_type) у
    // Python.
    // Знак ? тут позначає невідомий конкретний тип у параметрі Class, а не вибір через ? :; extends обмежує його
    // підкласами Throwable.
    private static void expect(Class<? extends Throwable> type, Action action) { // Перевіряємо, що помилкові дані дають саме потрібний вид помилки.
        try { action.run(); } // Виконуємо потенційно помилкову операцію.
        // catch — аналог except у Python: ця гілка виконується лише після відповідної помилки в try. e — об’єкт
        // винятку, getMessage() дає його пояснення; вертикальна риска між типами дозволяє одним блоком обробити
        // кілька видів помилок.
        catch (Throwable error) { check(type.isInstance(error)); return; } // Неправильний тип винятку теж провалює тест.
        throw new AssertionError("Очікували " + type.getSimpleName()); // Відсутність потрібного винятку є помилкою реалізації.
    }
    // public дозволяє Java знайти точку входу; static означає виклик без new Main(); void означає, що метод не
    // повертає значення. String[] args — масив аргументів запуску без назви програми (на відміну від Python
    // sys.argv). Тут починається виконання, приблизно як у блоці if __name__ == "__main__" у Python.
    public static void main(String[] args) throws Exception { // Метод запускає усі перевірки цієї лабораторної.
        Organization owner = new Factory("Test","Test",1); // Тестовий власник з ієрархії лабораторної 3.
        // new тип[...] створює масив фіксованої довжини: додати елемент через append, як у Python list, не можна.
        // Числові клітинки без явних значень спочатку дорівнюють 0, boolean — false, а посилання на об’єкти —
        // null. Індекси починаються з 0; вихід за межі спричиняє виняток.
        // Це for-each: двокрапка означає «взяти по черзі кожен елемент», як for item in items у Python. Ліворуч
        // указано тип елемента; сам індекс тут не потрібен, а для об’єктів змінна отримує посилання, не копію.
        for (boolean truck : new boolean[]{true,false}) { // Перевіряємо обидва види машин.
            // У for спочатку один раз задається лічильник, перед кожним проходом перевіряється умова, а після
            // проходу виконується i++ або j++. Умова i < n відповідає Python range(n): значення n вже не входить у
            // цикл.
            for (int seed = 0; seed < 100; seed++) { // Різні початкові позиції охоплюють рух і народження всередині цільової області.
                // Зерно seed задає відтворювану послідовність псевдовипадкових чисел. Однакове зерно й однаковий
                // порядок викликів дають той самий початок симуляції; це допомагає повторювати перевірки.
                Vehicle v = new Vehicle(seed,owner,truck,new java.util.Random(seed)); // Створюємо відтворюваний початковий стан.
                Position before = v.snapshot(); // Фіксуємо початок і ціль.
                // Умова ? значення_якщо_так : значення_якщо_ні — короткий вибір одного з двох значень, аналог a if
                // condition else b у Python. Обчислюється лише вибрана частина, тому інший конструктор чи виклик
                // тут не виконується.
                // Координати відлічуються від верхнього лівого кута: менший y означає вище. Для вантажівки цільова
                // чверть верхня ліва, для легкової — нижня права; середні лінії включено умовами <= та >=.
                boolean inside = truck ? before.x()<=380 && before.y()<=220 : before.x()>=380 && before.y()>=220; // Незалежно перевіряємо чверть народження.
                if (inside) check(before.arrived()); // Народжена в цільовій чверті машина повинна одразу стояти.
                check(truck ? before.targetX()<=380 && before.targetY()<=220 : before.targetX()>=380 && before.targetY()>=220); // Ціль завжди у потрібній чверті.
                v.move(100,100); // Великий крок повинен завершитись точно в цілі без проскоку.
                Position after = v.snapshot(); // Отримуємо результат руху.
                check(after.arrived()); near(after.x(),after.targetX()); near(after.y(),after.targetY()); // Машина зупинилася в кінцевій точці.
                // equals(...) порівнює вміст за правилом відповідного класу. Для рядків не слід писати ==, бо в
                // Java він порівнює посилання; Python == для рядків уже порівнює текст. Для власних об’єктів
                // правило equals визначено в їхньому класі.
                v.move(100,1); check(v.snapshot().equals(after)); // Після прибуття рух не відновлюється.
            }
        }
        TruckAI ai = new TruckAI(owner); // Перевіряємо протокол реального потоку.
        // Thread.start() запускає окремий потік, у якому JVM викличе run(). Звичайний виклик run() виконав би код
        // у поточному потоці без паралельного запуску. Той самий об’єкт Thread можна запустити лише один раз.
        ai.setPaused(true); ai.start(); // Запускаємо потік у стані очікування.
        try { // Завершення гарантоване навіть при помилці перевірки.
            java.util.List<Position> first = ai.snapshots(); // Знімок до відновлення.
            // sleep призупиняє ПОТОЧНИЙ потік на задану кількість мілісекунд і може кинути InterruptedException.
            // Інші потоки працюють далі; на відміну від wait, sleep не віддає вже захоплених замків, тому в BaseAI
            // він стоїть поза synchronized.
            Thread.sleep(60); check(ai.snapshots().equals(first)); // На паузі координати не змінюються.
            // Пріоритет 1..10 — побажання для планувальника ОС, а не гарантована частка процесора чи множник
            // швидкості. Фізичну швидкість машин визначає speed(), тому підвищення пріоритету не означає
            // пропорційно швидший рух.
            ai.setPriority(3); check(ai.getPriority()==3); // Параметр пріоритету має зберігатися.
            ai.setPaused(false); // Пробуджуємо потік через notifyAll.
            // nanoTime — годинник для вимірювання проміжків, як time.perf_counter_ns() у Python. Його значення не
            // є календарною датою; зміст має різниця двох показів, яку не збиває переведення системного годинника.
            // Суфікс L робить літерал типом long — 64-бітним цілим; підкреслення служать лише для читання.
            // Deadline обмежує очікування тесту, щоб помилка потоку не змусила перевірку висіти безкінечно.
            long deadline = System.nanoTime()+2_000_000_000L; // Обмежуємо час очікування тесту двома секундами.
            while (ai.snapshots().equals(first) && System.nanoTime()<deadline) Thread.sleep(10); // Чекаємо фактичного кроку, а не конкретного розкладу ОС.
            check(!ai.snapshots().equals(first)); // Після відновлення машини мають рухатися.
            ai.setPaused(true); java.util.List<Position> frozen = ai.snapshots(); // setPaused повертає лише після узгодження з поточним кроком.
            Thread.sleep(60); check(ai.snapshots().equals(frozen)); // Повторна пауза також стабільна.
        // finally виконується і після успіху, і при виході через виняток. Як у Python try/finally, тут це гарантує
        // прибирання тимчасового файлу або запит на завершення робочих потоків.
        // join чекає завершення вибраного потоку, приблизно як threading.Thread.join() у Python. Виклик із числом
        // обмежує очікування мілісекундами, тому після нього тест ще перевіряє isAlive(); без аргументу чекаємо до
        // завершення.
        } finally { ai.shutdown(); ai.join(2000); } // Завершуємо навіть потік, який перебуває у wait.
        check(!ai.isAlive()); // Після закриття не повинно лишитися фонового потоку.
        System.out.println("OK: " + count + " перевірок"); // Видимий підсумок після успішного виконання.
    }
}
